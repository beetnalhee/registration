-- 검색 인덱스는 nickname 을 포함하고 있어 컬럼과 함께 사라진다.
-- 먼저 명시적으로 지우고, 이름만으로 다시 만든다.
drop index if exists participants_search_idx;

alter table participants drop column if exists nickname;

create index if not exists participants_search_idx on participants (name);
